const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-webgl','--no-sandbox']});
 try{
  const page=await browser.newPage({viewport:{width:1380,height:900},ignoreHTTPSErrors:true});
  const errors=[];
  page.on('pageerror',e=>{errors.push(e.stack||e.message);console.error('JS_ERROR',e.stack||e.message)});
  page.on('console',msg=>{if(msg.type()==='error'){errors.push(msg.text());console.error('CONSOLE_ERROR',msg.text())}});
  page.on('requestfailed',r=>console.error('NETWORK_ERROR',r.url(),r.failure()?.errorText));
  const base=process.env.SMOKE_URL||'http://127.0.0.1:4173';
  const response=await page.goto(base,{waitUntil:'networkidle',timeout:40000});
  if(!response||response.status()!==200)throw Error('Unexpected HTTP status '+response?.status());
  await page.waitForFunction(()=>window.__nexoBootReady===true,{timeout:40000}).catch(async()=>{throw Error('BOOT FAILURE: '+await page.locator('#bootStatus').textContent()+'\n'+errors.join('\n'))});
  if(await page.locator('#startBtn').isDisabled())throw Error('Start button is disabled');
  console.log('PASS: Engine ready');
  await page.locator('#startBtn').click({timeout:12000});
  await page.waitForFunction(()=>document.querySelector('#start')?.classList.contains('hidden'),{timeout:8000});
  console.log('PASS: Entered world');
  if(!await page.locator('#rpWelcomeFlash').evaluate(e=>e.classList.contains('show')))throw Error('RP welcome announcement missing');
  await page.locator('#rpNewsToggle').click();
  await page.locator('#rpNewsClose').click();
  if(!await page.locator('#rpNews').evaluate(e=>e.hidden))throw Error('News dismiss failed');
  await page.locator('[data-rp-page="avatar"]').click();
  if(!await page.locator('#panel h2').textContent().then(s=>s.includes('KREATOR')))throw Error('RP avatar editor not opening');
  await page.locator('[data-rp-page="animations"]').click();
  await page.locator('[data-emote="salute"]').click();
  await page.locator('[data-rp-page="bag"]').click();
  if(!await page.locator('#panel h2').textContent().then(s=>s.includes('PLECAK')))throw Error('RP tools menu not opening');
  console.log('PASS: Original RP welcome, updates and functional quick actions');
  if(!await page.locator('#taskTitle').textContent().then(s=>s.includes('Witaj')))throw Error('Free roleplay mode not enabled');
  await page.locator('[data-quick="homes"]').click();
  await page.locator('[data-claim]').first().click();
  await page.locator('[data-house-style="modern"]').click();
  if(!await page.locator('[data-house-style="modern"]').isDisabled())throw Error('House style not saved');
  await page.locator('[data-interior="luxury"]').click();
  if(!await page.locator('[data-interior="luxury"]').isDisabled())throw Error('Interior theme not saved');
  await page.locator('[data-decor="tv"]').click();
  await page.locator('[data-decor="lamp"]').click();
  if(await page.locator('[data-decor-remove]').count()!==2)throw Error('Furniture placement not saved');
  await page.locator('[data-house-enter]').click();
  await page.waitForFunction(()=>document.querySelector('#mode')?.textContent.includes('W DOMU'),{timeout:8000});
  await page.keyboard.press('e');
  await page.waitForFunction(()=>document.querySelector('#mode')?.textContent.includes('SPACER'),{timeout:8000});
  console.log('PASS: House claim, style, customizable furniture, house enter and exit');
  await page.locator('[data-rp-page="family"]').click();
  await page.locator('#familyName').fill('Rodzina Testowa');
  await page.locator('[data-family-save]').click();
  await page.locator('[data-family-role="Rodzeństwo"]').click();
  if(!await page.locator('#panel h2').textContent().then(t=>t.includes('RODZINA')))throw Error('Family controls missing');
  await page.locator('[data-rp-page="cameras"]').click();
  await page.locator('[data-home-camera="front"]').click();
  await page.waitForFunction(()=>document.querySelector('#rpCameraOverlay')?.classList.contains('visible'),null,{timeout:5000});
  await page.locator('#rpCameraExit').click();
  if(await page.locator('#rpCameraOverlay').evaluate(e=>e.classList.contains('visible')))throw Error('Home camera cannot be stopped');
  console.log('PASS: Family roles and three-camera home surveillance views');
  await page.locator('[data-quick="cars"]').click();
  if(await page.locator('[data-spawn]').count()!==10)throw Error('Vehicle catalog is not 10 items');
  await page.locator('[data-spawn="5"]').click();
  await page.locator('[data-drive="5"]').click();
  await page.waitForFunction(()=>document.querySelector('#mode')?.textContent.includes('PROWADZENIE'),{timeout:8000});
  await page.keyboard.press('e');
  await page.waitForFunction(()=>document.querySelector('#mode')?.textContent.includes('SPACER'),{timeout:8000});
  console.log('PASS: Ten-car garage, ambulance and instant driving');
  await page.locator('#menuExpand').click();
  await page.locator('[data-page="jobs"]').click();
  await page.locator('[data-delivery]').click();
  if(!await page.locator('#taskTitle').textContent().then(s=>s.includes('Kurier')))throw Error('Delivery activation failed');
  await page.locator('[data-delivery]').click();
  if(!await page.locator('#taskTitle').textContent().then(s=>s.includes('Witaj')))throw Error('Delivery deactivation failed');
  console.log('PASS: Freeplay and optional delivery');
  await page.locator('#menuExpand').click();
  await page.locator('[data-page="places"]').click();
  if(await page.locator('[data-visit]').count()<8)throw Error('City guide too small');
  await page.locator('[data-visit="0"]').click();
  await page.keyboard.press('e');
  if(!await page.locator('[data-place-action]').count())throw Error('Building interaction missing');
  console.log('PASS: City guide and location interaction');
  await page.waitForTimeout(1500);
  if(errors.length)throw Error(errors.join('\n'));
  console.log('PASS: All desktop interactions without JavaScript errors');
  await page.close(); // Release the WebGL context before starting the mobile GPU test.
  const mobile=await browser.newPage({viewport:{width:420,height:903},isMobile:true,hasTouch:true,ignoreHTTPSErrors:true});
  const mobileErrors=[];
  mobile.on('pageerror',e=>mobileErrors.push(e.stack||e.message));
  await mobile.goto(base,{waitUntil:'networkidle',timeout:40000});
  await mobile.waitForFunction(()=>window.__nexoBootReady===true,null,{timeout:55000}).catch(async()=>{throw Error('Mobile boot failed: '+await mobile.locator('#bootStatus').textContent()+'; errors: '+mobileErrors.join('; '))});
  const navBefore=await mobile.evaluate(()=>({sidebar:getComputedStyle(document.querySelector('.sidebar')).display,quick:getComputedStyle(document.querySelector('.quickbar')).display,bounds:document.querySelector('.quickbar').getBoundingClientRect().toJSON(),height:innerHeight}));
  if(navBefore.sidebar!=='none')throw Error('Regression: giant sidebar covers the mobile game: '+JSON.stringify(navBefore));
  if(navBefore.quick==='none'||navBefore.bounds.bottom>navBefore.height+2||navBefore.bounds.top<navBefore.height*.65)throw Error('Mobile dock out of screen: '+JSON.stringify(navBefore));
  console.log('PASS: Mobile sidebar hidden by default and bottom dock visible');
  await mobile.locator('#startBtn').click({timeout:12000});
  await mobile.locator('#rpToolsToggle').click({timeout:8000});
  if(!await mobile.locator('#rpTools').evaluate(e=>e.classList.contains('open')))throw Error('Mobile RP right panel not expandable');
  await mobile.locator('[data-rp-page="animations"]').click({timeout:8000});
  if(!await mobile.locator('#panel h2').textContent().then(s=>s.includes('ANIMACJE')))throw Error('Mobile RP animations panel broken');
  if(await mobile.locator('#rpTools').evaluate(e=>e.classList.contains('open')))throw Error('Mobile RP actions did not collapse');
  console.log('PASS: Mobile compact RP menu and animation actions');
  await mobile.locator('[data-quick="homes"]').click({timeout:8000});
  if(!await mobile.locator('#panel').evaluate(e=>e.classList.contains('visible')))throw Error('Mobile quickbar cannot open houses');
  await mobile.locator('#menuExpand').click({timeout:8000});
  const rect=await mobile.locator('.sidebar').boundingBox();if(!rect||rect.width>310||rect.height>mobile.viewportSize().height*.9)throw Error('Expanded sidebar too large: '+JSON.stringify(rect));
  if(!await mobile.locator('.sidebar').evaluate(e=>e.classList.contains('expanded')))throw Error('Mobile more-menu did not expand');
  await mobile.locator('[data-page="jobs"]').click({timeout:8000});
  if(!await mobile.locator('#panel').evaluate(e=>e.classList.contains('visible')))throw Error('Mobile expanded menu cannot open job panel');
  if(mobileErrors.length)throw Error('Mobile errors: '+mobileErrors.join('\n'));
  console.log('PASS: Mobile touch quickbar, expandable navigation and job panel');
  await mobile.close();
  console.log('SUCCESS: Desktop and mobile browser smoke tests passed');
 }finally{await browser.close()}
})().catch(e=>{console.error(e.stack||e);process.exitCode=1});
