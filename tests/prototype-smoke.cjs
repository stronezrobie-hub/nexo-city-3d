const { chromium } = require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--use-gl=angle','--use-angle=swiftshader','--enable-webgl','--no-sandbox']});
 try {
  const pc=await browser.newPage({viewport:{width:1365,height:768},ignoreHTTPSErrors:true});
  const errors=[];
  pc.on('pageerror',e=>errors.push(e.stack||e.message));
  pc.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
  await pc.goto('http://127.0.0.1:4173',{waitUntil:'networkidle',timeout:30000});
  await pc.waitForFunction(()=>window.__nexoBootReady===true,null,{timeout:40000});
  if(await pc.locator('#start-button').isDisabled())throw Error('Start unavailable');
  await pc.locator('#start-button').click();
  if(await pc.locator('#start-screen').isVisible())throw Error('Start overlay still visible');
  await pc.waitForTimeout(700);
  await pc.screenshot({path:'/tmp/nexo-prototype-desktop.png'});
  let initial=await pc.evaluate(()=>window.__nexoDebug?.position||null);
  await pc.keyboard.down('w');await pc.waitForTimeout(1000);await pc.keyboard.up('w');
  await pc.waitForTimeout(1300);
  const pos=await pc.evaluate(()=>window.__nexoDebug?.position||null);
  console.log('Desktop player movement',initial,pos);
  if(!pos||pos[2]<initial[2]+.2)throw Error('Player failed to move towards house');
  await pc.locator('[data-panel="dom"]').click();
  await pc.locator('[data-home]').click();
  await pc.waitForTimeout(500);
  await pc.keyboard.press('e');
  await pc.waitForTimeout(900);
  const door=await pc.evaluate(()=>window.__nexoDebug?.doorOpen);
  if(!door)throw Error('Cannot open door with E');
  console.log('Door opened with E');
  await pc.keyboard.down('w');await pc.waitForTimeout(3100);await pc.keyboard.up('w');
  await pc.waitForTimeout(1400);
  const inside=await pc.evaluate(()=>window.__nexoDebug?.position||null);
  if(!inside||inside[2]<27)throw Error('Cannot enter home without loading');
  console.log('Inside same scene',inside);
  await pc.screenshot({path:'/tmp/nexo-prototype-home.png'});
  await pc.locator('[data-panel="grafika"]').click();
  await pc.locator('[data-quality="niska"]').click();
  const saved=await pc.evaluate(()=>JSON.parse(localStorage.getItem('nexo-life-rp-ts-v1')||'{}').quality);
  if(saved!=='niska')throw Error('Quality profile not saved');
  await pc.locator('[data-panel="grafika"]').click();
  await pc.locator('[data-panel="postac"]').click();
  await pc.locator('[data-color="15896694"]').count().catch(()=>{});
  if(await pc.locator('[data-color]').count()!==6)throw Error('Character editor missing');
  if(errors.length)throw Error('Desktop errors: '+errors.join(' | '));
  console.log('PASS: desktop start, movement, entering house, quality saving and avatar editor');
  await pc.close();
  const phone=await browser.newPage({viewport:{width:390,height:844},hasTouch:true,isMobile:true,ignoreHTTPSErrors:true});
  const mobileErrors=[];phone.on('pageerror',e=>mobileErrors.push(e.message));
  await phone.goto('http://127.0.0.1:4173',{waitUntil:'domcontentloaded',timeout:30000});
  await phone.waitForFunction(()=>window.__nexoBootReady===true,null,{timeout:40000});
  await phone.locator('#start-button').click();
  if(!await phone.locator('.mobile-controls').isVisible())throw Error('Touch controls not visible');
  if(!await phone.locator('.dock').isVisible())throw Error('Mobile dock not visible');
  await phone.screenshot({path:'/tmp/nexo-prototype-mobile.png'});
  await phone.locator('[data-control="up"]').dispatchEvent('pointerdown',{pointerId:42,pointerType:'touch',clientX:100,clientY:700});
  await phone.waitForTimeout(500);
  await phone.locator('[data-control="up"]').dispatchEvent('pointerup',{pointerId:42,pointerType:'touch',clientX:100,clientY:700});
  await phone.locator('[data-panel="dom"]').click();
  if(!await phone.locator('#menu-panel').isVisible())throw Error('Mobile home menu missing');
  if(mobileErrors.length)throw Error('Mobile errors: '+mobileErrors.join(' | '));
  console.log('PASS: mobile start, controls and responsive menu');
 } finally { await browser.close(); }
})().catch(e=>{console.error('TEST FAILED',e.stack||e);process.exitCode=1});
